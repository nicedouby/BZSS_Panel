// -*- coding: utf-8 -*-

import fs from "node:fs/promises";
import path from "node:path";

/**
 * Match Snapshot Plugin (对局快照插件)
 * 
 * 功能：
 * 当对局结束时（通过日志 DetermineMatchWinner 或 RCON MATCH_END 触发），
 * 自动抓取当前所有玩家和队伍的状态，并保存为 JSON 和 Markdown 文件。
 */

const PLUGIN_ID = "match-snapshot";
const SNAPSHOT_DIR = "./data/match-snapshots";

export function createPlugin({ core, modules, config, logger } = {}) {
  const pluginLogger = logger ?? core.createLogger?.({
    moduleId: PLUGIN_ID,
    source: PLUGIN_ID,
    channel: "plugin",
  }) ?? core.logger;

  async function takeSnapshot(triggerEvent) {
    pluginLogger.info(`Taking match snapshot triggered by ${triggerEvent.eventName || "event"}...`);

    try {
      // 确保目录存在
      await fs.mkdir(SNAPSHOT_DIR, { recursive: true });

      // 获取当前完整状态
      const overview = modules.matchState?.api?.getOverview?.();
      if (!overview) {
        pluginLogger.warn("Failed to get match overview from matchState module.");
        return;
      }

      const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
      const mapName = overview.match?.map || "UnknownMap";
      const fileNameBase = `Match-${mapName}-${timestamp}`;

      // 1. 保存 JSON 快照
      const jsonPath = path.join(SNAPSHOT_DIR, `${fileNameBase}.json`);
      await fs.writeFile(jsonPath, JSON.stringify(overview, null, 2), "utf8");

      // 2. 生成并保存 Markdown 报告 (模拟“截图”效果的数据展示)
      const mdReport = generateMarkdownReport(overview, triggerEvent);
      const mdPath = path.join(SNAPSHOT_DIR, `${fileNameBase}.md`);
      await fs.writeFile(mdPath, mdReport, "utf8");

      pluginLogger.info(`Match snapshot saved: ${fileNameBase}`);
    } catch (error) {
      pluginLogger.error(`Failed to take match snapshot: ${error.stack || error}`);
    }
  }

  async function listSnapshots() {
    try {
      await fs.mkdir(SNAPSHOT_DIR, { recursive: true });
      const files = await fs.readdir(SNAPSHOT_DIR);
      const snapshots = [];

      for (const file of files) {
        if (!file.endsWith(".json")) continue;
        const stats = await fs.stat(path.join(SNAPSHOT_DIR, file));
        snapshots.push({
          id: file,
          name: file.replace(".json", ""),
          createdAt: stats.mtime.toISOString(),
          size: stats.size,
        });
      }

      return snapshots.sort((a, b) => b.createdAt.localeCompare(a.createdAt));
    } catch (error) {
      pluginLogger.error(`Failed to list snapshots: ${error.message}`);
      return [];
    }
  }

  function generateMarkdownReport(overview, triggerEvent) {
    const { match, players, squads } = overview;
    const now = new Date().toLocaleString();
    
    let md = `# Match Snapshot Report\n\n`;
    md += `- **Time**: ${now}\n`;
    md += `- **Map**: ${match?.map || "Unknown"}\n`;
    md += `- **Layer**: ${match?.layer || "Unknown"}\n`;
    md += `- **Mode**: ${match?.mode || "Unknown"}\n`;
    md += `- **Trigger**: ${triggerEvent.eventName} (${triggerEvent.winner || "No winner info"})\n\n`;

    const teams = [1, 2];
    for (const teamId of teams) {
      md += `## Team ${teamId}\n\n`;
      
      const teamSquads = squads.filter(s => s.teamID === teamId);
      const unassignedPlayers = players.filter(p => p.teamID === teamId && !p.squadID);

      for (const squad of teamSquads) {
        md += `### Squad ${squad.squadID}: ${squad.squadName} (${squad.size} members)\n`;
        md += `| Name | Role | Leader | SteamID | EOSID |\n`;
        md += `| :--- | :--- | :--- | :--- | :--- |\n`;
        
        const squadMembers = players.filter(p => p.teamID === teamId && p.squadID === squad.squadID);
        for (const p of squadMembers) {
          md += `| ${p.name} | ${p.role} | ${p.isLeader ? "⭐" : ""} | ${p.steamID || "-"} | ${p.eosID || "-"} |\n`;
        }
        md += `\n`;
      }

      if (unassignedPlayers.length > 0) {
        md += `### Unassigned Players (Team ${teamId})\n`;
        md += `| Name | Role | SteamID | EOSID |\n`;
        md += `| :--- | :--- | :--- | :--- |\n`;
        for (const p of unassignedPlayers) {
          md += `| ${p.name} | ${p.role} | ${p.steamID || "-"} | ${p.eosID || "-"} |\n`;
        }
        md += `\n`;
      }
    }

    md += `---\n*Snapshot generated by BZSS Match Snapshot Plugin*`;
    return md;
  }

  const api = {
    listSnapshots,
    takeManualSnapshot: () => takeSnapshot({ eventName: "MANUAL_TRIGGER" }),
  };

  return {
    manifest: {
      id: PLUGIN_ID,
      name: "对局快照",
      kind: "plugin",
      version: "1.1.0",
      description: "当对局结束时，自动保存所有玩家和队伍的状态快照到本地文件夹。",
    },
    apiName: "matchSnapshot",
    api,

    async start() {
      if (core.eventBus?.onCoreEvent) {
        core.eventBus.onCoreEvent("round.match_winner", (event) => takeSnapshot(event));
      }

      if (core.eventBus?.onCoreEvent) {
        core.eventBus.onCoreEvent("MATCH_END", (event) => takeSnapshot(event));
      }

      const enableDebug = config.get("web.enableDebugPage", false);
      if (enableDebug) {
        core.webRegistry?.registerPage?.({
          id: `web.${PLUGIN_ID}.debug`,
          title: "快照录制",
          group: "调试",
          route: "/debug/match-snapshots",
          pageModule: `/pages/match-snapshot-debug.js`,
          source: PLUGIN_ID,
          description: "查看和管理已录制的对局快照。",
          required: false,
          enabled: true,
          order: 999,
          icon: "📸",
        });
      }

      pluginLogger.info(`[MatchSnapshot] Plugin started${enableDebug ? " with debug page" : ""}.`);
    },

    async stop() {
      pluginLogger.info("[MatchSnapshot] Plugin stopped.");
    }
  };
}
